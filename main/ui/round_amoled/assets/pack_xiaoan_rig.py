"""Pack the half-body XiaoAn cutouts into LVGL RGB565A8 planes and an index."""

import struct
from pathlib import Path

from PIL import Image

ASSETS = Path(__file__).resolve().parent


def fit(sprite: Image.Image, size: tuple[int, int]) -> Image.Image:
    alpha = sprite.getchannel("A")
    bounds = alpha.point(lambda value: 255 if value >= 20 else 0).getbbox()
    if not bounds:
        raise ValueError("A rig cutout is empty or lacks alpha")
    sprite = sprite.crop(bounds)
    sprite.thumbnail(size, Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", size)
    canvas.alpha_composite(sprite, ((size[0] - sprite.width) // 2, (size[1] - sprite.height) // 2))
    return canvas


def load_alpha(path: Path) -> Image.Image:
    with Image.open(path) as image:
        if "A" not in image.getbands():
            raise ValueError(f"{path.name} must have an alpha channel")
        low, high = image.getchannel("A").getextrema()
        if low != 0 or high < 245:
            raise ValueError(f"{path.name} must contain transparent and nearly opaque pixels")
        return image.convert("RGBA")


def prepare_parts(atlas: Image.Image, torso: Image.Image) -> dict[str, Image.Image]:
    if atlas.width % 3 or atlas.height % 3:
        raise ValueError("Expected a uniform 3 by 3 atlas")
    w, h = atlas.width // 3, atlas.height // 3

    def cell(row: int, col: int) -> Image.Image:
        return atlas.crop((col * w, row * h, (col + 1) * w, (row + 1) * h))

    def eyes(source: Image.Image, left_size: tuple[int, int], right_size: tuple[int, int]) -> Image.Image:
        layer = Image.new("RGBA", (80, 48))
        for region, size, center in (
            ((0, 0, w // 2, h), left_size, (18, 24)),
            ((w // 2, 0, w, h), right_size, (64, 20)),
        ):
            sprite = fit(source.crop(region), size)
            layer.alpha_composite(sprite, (center[0] - size[0] // 2, center[1] - size[1] // 2))
        return layer

    def mouth(row: int, col: int, size: tuple[int, int]) -> Image.Image:
        sprite = fit(cell(row, col), size)
        layer = Image.new("RGBA", (30, 24))
        layer.alpha_composite(sprite, ((30 - sprite.width) // 2, (24 - sprite.height) // 2))
        return layer

    return {
        "Head": fit(cell(0, 0), (178, 160)),
        "Torso": fit(torso, (118, 74)),
        "LeftArm": fit(cell(0, 2), (46, 62)),
        "RightArm": fit(cell(1, 0), (46, 62)),
        "EyesOpen": eyes(cell(1, 1), (18, 25), (17, 24)),
        "EyesClosed": eyes(cell(1, 2), (19, 8), (18, 8)),
        "Smile": mouth(2, 0, (24, 10)),
        "Speaking": mouth(2, 1, (26, 17)),
        "Thinking": mouth(2, 2, (21, 9)),
    }


def pack(parts: dict[str, Image.Image]) -> tuple[bytes, str]:
    blob = bytearray()
    members = []
    for name, sprite in parts.items():
        blob.extend(bytes(-len(blob) % 4))
        members.append(
            f"inline constexpr RigImage k{name}{{{len(blob)}, {sprite.width}, {sprite.height}}};"
        )
        rgba = sprite.tobytes()
        for r, g, b in zip(rgba[0::4], rgba[1::4], rgba[2::4]):
            color = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            blob.extend(struct.pack("<H", color))
        blob.extend(rgba[3::4])

    header = "\n".join((
        "// Generated by assets/pack_xiaoan_rig.py. Do not edit by hand.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace agentsphere::xiaoan_assets {",
        "",
        "struct RigImage {",
        "    uint32_t offset;",
        "    uint16_t width;",
        "    uint16_t height;",
        "};",
        "",
        *members,
        "",
        f"inline constexpr uint32_t kRigDataBytes = {len(blob)};",
        "",
        "}  // namespace agentsphere::xiaoan_assets",
        "",
    ))
    return bytes(blob), header


if __name__ == "__main__":
    sprites = prepare_parts(load_alpha(ASSETS / "xiaoan_rig_atlas.png"),
                            load_alpha(ASSETS / "xiaoan_rig_torso.png"))
    data, index = pack(sprites)
    (ASSETS / "xiaoan_rig.rgb565a8").write_bytes(data)
    (ASSETS.parent / "xiaoan_rig_assets.h").write_text(index, encoding="utf-8")
